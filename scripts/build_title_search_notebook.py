"""Generate src/notebooks/kaggle_title_search.ipynb, the RTX Pro 6000 job for scripts/title_search.py.

    uv run python scripts/build_title_search_notebook.py
"""
import argparse
import json
from pathlib import Path

from build_chunk_notebook import copied_source, notebook


def build_cells():
    return [
        ('md', """
# MedXIR: title search + document rerank of the new documents

Generated by `scripts/build_title_search_notebook.py`. Edit the generator, not this file.

RTX Pro 6000, Internet OFF. Attach chunk corpus v2, `query.parquet`, `doc_rank.parquet` of the current best
pipeline, packaged Qwen3-Embedding-8B and bge-reranker-v2-m3, and (optional) the rewrite run's `query_rewrites.json`.
The code cell is a copy of `scripts/title_search.py`; outputs `title_candidates.parquet`, `title_manifest.json`.
"""),
        ('code', '# Copied from scripts/title_search.py by scripts/build_title_search_notebook.py. Edit the script and rebuild.\n'
                 + copied_source(Path('scripts') / 'title_search.py')),
        ('code', 'main()\n'),
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--output', type=Path, default=Path('src/notebooks/kaggle_title_search.ipynb'))
    args = parser.parse_args()
    cells = build_cells()
    args.output.write_text(json.dumps(notebook(cells), ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print(f'{args.output}: {len(cells)} cells')


if __name__ == '__main__':
    main()
