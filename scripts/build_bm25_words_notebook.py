"""Generate src/notebooks/kaggle_bm25_words.ipynb, the Kaggle CPU job for scripts/bm25_words.py.

The notebook installs pyvi (Internet ON, CPU session), copies scripts/bm25_words.py into a code cell and runs
main() with pyvi's ViTokenizer. Outputs in /kaggle/working: bm25w-chunks-k500.npz, bm25w-texts-k500.npz,
medxir-bm25w-d30/d40-submission.zip, bm25w_manifest.json.

    uv run python scripts/build_bm25_words_notebook.py
"""
import argparse
import json
from pathlib import Path

from build_chunk_notebook import copied_source, notebook


def build_cells():
    return [
        ('md', """
# MedXIR: BM25 over Vietnamese words (the organizers' baseline recipe)

Generated by `scripts/build_bm25_words_notebook.py`. Edit the generator, not this file.

CPU job, Internet ON (pip install pyvi). Attach `ntklinhfitus/medxir-chunk-corpus-v2` and
`boinhbo/medxir-retrieval-inputs` (`query.parquet`). The second code cell is a copy of `scripts/bm25_words.py`.
"""),
        ('code', """
import subprocess
import sys

subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', 'pyvi'], check=True)
"""),
        ('code', '# Copied from scripts/bm25_words.py by scripts/build_bm25_words_notebook.py. Edit the script and rebuild.\n'
                 + copied_source(Path('scripts') / 'bm25_words.py')),
        ('code', """
from pyvi import ViTokenizer

main(ViTokenizer.tokenize, workers=4)
"""),
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--output', type=Path, default=Path('src/notebooks/kaggle_bm25_words.ipynb'))
    args = parser.parse_args()
    cells = build_cells()
    args.output.write_text(json.dumps(notebook(cells), ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print(f'{args.output}: {len(cells)} cells')


if __name__ == '__main__':
    main()
