"""Generate src/notebooks/kaggle_translate_queries.ipynb, the Kaggle GPU job for scripts/translate_queries.py.

GPU with Internet ON (the model comes from Hugging Face). Output: query_translations.json.

    uv run python scripts/build_translate_notebook.py
"""
import argparse
import json
from pathlib import Path

from build_chunk_notebook import copied_source, notebook


def build_cells(tasks, out_name):
    return [
        ('md', """
# MedXIR: translate the queries to English and Chinese

Generated by `scripts/build_translate_notebook.py`. Edit the generator, not this file.

GPU, Internet ON. Attach `boinhbo/medxir-retrieval-inputs` (`query.parquet`). The code cell is a copy of
`scripts/translate_queries.py`; output `query_translations.json`.
"""),
        ('code', '# Copied from scripts/translate_queries.py by scripts/build_translate_notebook.py. Edit the script and rebuild.\n'
                 + copied_source(Path('scripts') / 'translate_queries.py')),
        ('code', f'main(tasks={tuple(tasks)!r}, out_name={out_name!r})\n'),
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--output', type=Path, default=Path('src/notebooks/kaggle_translate_queries.ipynb'))
    parser.add_argument('--tasks', default='en,zh', help="comma list of translate_queries.TASKS keys; 'vq' = rewrite")
    parser.add_argument('--out-name', default='query_translations.json')
    args = parser.parse_args()
    cells = build_cells(args.tasks.split(','), args.out_name)
    args.output.write_text(json.dumps(notebook(cells), ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    print(f'{args.output}: {len(cells)} cells')


if __name__ == '__main__':
    main()
